//! Privacy-safe, bounded solver-run telemetry.
//!
//! This is intentionally separate from the per-school/account execution and
//! billing ledgers in `serverless.rs`.  It must never store a timetable,
//! request body, school/account/user identifier, raw error, or browser event
//! identifier.  The only durable event key is a one-way digest used for
//! idempotency.  Super Admin receives aggregates only.

use crate::db::Db;
use rusqlite::{params, OptionalExtension};
use serde_json::{json, Map, Value};
use sha2::{Digest, Sha256};
use std::collections::{BTreeMap, HashMap};
use std::sync::{Arc, Mutex, OnceLock};
use std::time::{Instant, SystemTime, UNIX_EPOCH};

pub const FET_EVENT_MAX_BODY_BYTES: usize = 8 * 1024;
const RETENTION_MS: u64 = 90 * 24 * 60 * 60 * 1_000;
const MAX_EVENT_ROWS: i64 = 100_000;
const RATE_WINDOW_MS: u64 = 60 * 60 * 1_000;
const FET_EVENTS_PER_WINDOW: u32 = 120;
const MAX_RUNTIME_MS: u64 = 24 * 60 * 60 * 1_000;
const MAX_METRIC_VALUE: i64 = 1_000_000_000;
const MAX_COST_USD: f64 = 1_000.0;

#[derive(Clone, Debug)]
pub struct ServerRunMetadata {
    pub executor: String,
    pub focus: String,
    pub gap_target: String,
    pub budget_kind: String,
    pub budget_seconds: u64,
    /// Numeric UI baseline/target only.  These are aggregate-safe quality
    /// counters, never timetable cells or an identifier.
    pub metric_baseline: Option<i64>,
    pub target_metric: Option<i64>,
    pub profile: Option<String>,
    pub cloud_digest: Option<String>,
}

impl ServerRunMetadata {
    /// Copies a compact, canonical allowlist from solver settings.  The full
    /// request is deliberately not retained by this type or written to SQLite.
    pub fn from_request(
        executor: &str,
        request: Option<&Value>,
        profile: Option<&str>,
        cloud_digest: Option<&str>,
    ) -> Self {
        let executor = normalize_executor(executor).unwrap_or("vps").to_string();
        let settings = request
            .and_then(|request| request.get("settings"))
            .and_then(Value::as_object);
        let (focus, gap_target) = canonical_focus(settings);
        let (budget_kind, budget_seconds) = canonical_budget(&executor, settings);
        let metric_key = canonical_metric_key(&focus, &gap_target);
        let metric_baseline = metric_key
            .as_deref()
            .and_then(|key| metric_baseline_setting(settings, key));
        let target_metric = metric_key
            .as_deref()
            .and_then(|key| metric_target_setting(settings, key));
        Self {
            executor,
            focus,
            gap_target,
            budget_kind,
            budget_seconds,
            metric_baseline,
            target_metric,
            profile: profile.and_then(sanitize_profile),
            cloud_digest: cloud_digest.and_then(sanitize_digest),
        }
    }
}

/// An in-memory server-side attempt.  The opaque durable key is generated by
/// the caller-independent constructor, never from a job, account, school or
/// schedule ID.  A Drop fallback makes an unexpected coordinator exit visible
/// as a sanitised failed event instead of leaving a permanent `running` row.
pub struct ServerRun {
    db: Arc<Db>,
    key: String,
    metadata: ServerRunMetadata,
    started_at_ms: u64,
    started: Instant,
    finished: bool,
}

impl ServerRun {
    pub fn start(db: Arc<Db>, metadata: ServerRunMetadata) -> Self {
        let started_at_ms = now_millis();
        let key = generated_event_key();
        let run = Self {
            db,
            key,
            metadata,
            started_at_ms,
            started: Instant::now(),
            finished: false,
        };
        let _ = insert_server_start(&run.db, &run.key, &run.metadata, run.started_at_ms);
        run
    }

    pub fn finish(
        &mut self,
        outcome: &str,
        payload: Option<&Value>,
        fallback: Option<&str>,
        cost_estimate_usd: Option<f64>,
    ) {
        if self.finished {
            return;
        }
        let runtime_ms = self.started.elapsed().as_millis().min(u64::MAX as u128) as u64;
        let facts = TerminalFacts::from_payload(
            payload,
            &self.metadata.focus,
            &self.metadata.gap_target,
            self.metadata.metric_baseline,
            self.metadata.target_metric,
            outcome,
            fallback,
        );
        let _ = finish_server_run(&self.db, &self.key, runtime_ms, facts, cost_estimate_usd);
        self.finished = true;
    }
}

impl Drop for ServerRun {
    fn drop(&mut self) {
        if !self.finished {
            self.finish("failed", None, Some("coordinator_exit"), None);
        }
    }
}

