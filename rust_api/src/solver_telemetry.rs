#[derive(Default, Clone)]
struct AggregateDimension {
    total: u64,
    terminal: u64,
    completed: u64,
    failed: u64,
    cancelled: u64,
    released: u64,
    timeout: u64,
    no_improvement: u64,
    infeasible: u64,
    running: u64,
    hard_valid_known: u64,
    hard_valid_true: u64,
    applied_known: u64,
    applied_true: u64,
    target_known: u64,
    target_true: u64,
    floor_known: u64,
    floor_true: u64,
    metric_samples: u64,
    metric_delta_sum: i64,
    metric_before_sum: i64,
    metric_after_sum: i64,
    target_metric_samples: u64,
    target_metric_sum: i64,
    floor_metric_samples: u64,
    floor_metric_sum: i64,
    cost_estimate_usd: f64,
    runtimes: Vec<u64>,
}

impl AggregateDimension {
    fn add(&mut self, row: &TelemetryRow) {
        self.total += 1;
        match row.outcome.as_str() {
            "running" => self.running += 1,
            "completed" => {
                self.terminal += 1;
                self.completed += 1;
            }
            "failed" => {
                self.terminal += 1;
                self.failed += 1;
            }
            "cancelled" => {
                self.terminal += 1;
                self.cancelled += 1;
            }
            "released" => {
                self.terminal += 1;
                self.released += 1;
            }
            "timeout" => {
                self.terminal += 1;
                self.timeout += 1;
            }
            "no_improvement" => {
                self.terminal += 1;
                self.no_improvement += 1;
            }
            "infeasible" => {
                self.terminal += 1;
                self.infeasible += 1;
            }
            _ => {
                self.terminal += 1;
                self.failed += 1;
            }
        }
        if let Some(runtime) = row.runtime_ms {
            self.runtimes.push(runtime);
        }
        bool_count(
            row.hard_valid,
            &mut self.hard_valid_known,
            &mut self.hard_valid_true,
        );
        bool_count(row.applied, &mut self.applied_known, &mut self.applied_true);
        bool_count(
            row.target_reached,
            &mut self.target_known,
            &mut self.target_true,
        );
        bool_count(
            row.floor_reached,
            &mut self.floor_known,
            &mut self.floor_true,
        );
        if let Some(delta) = row.metric_delta {
            self.metric_samples += 1;
            self.metric_delta_sum = self.metric_delta_sum.saturating_add(delta);
            self.metric_before_sum = self
                .metric_before_sum
                .saturating_add(row.metric_before.unwrap_or(0));
            self.metric_after_sum = self
                .metric_after_sum
                .saturating_add(row.metric_after.unwrap_or(0));
        }
        if let Some(target) = row.target_metric {
            self.target_metric_samples += 1;
            self.target_metric_sum = self.target_metric_sum.saturating_add(target);
        }
        if let Some(floor) = row.floor_metric {
            self.floor_metric_samples += 1;
            self.floor_metric_sum = self.floor_metric_sum.saturating_add(floor);
        }
        self.cost_estimate_usd += row.cost_estimate_usd.unwrap_or(0.0).max(0.0);
    }

    fn json(&self) -> Value {
        let p50 = percentile(&self.runtimes, 0.50);
        let p95 = percentile(&self.runtimes, 0.95);
        json!({
            "total": self.total,
            "terminal": self.terminal,
            "completed": self.completed,
            "failed": self.failed,
            "cancelled": self.cancelled,
            "released": self.released,
            "timeout": self.timeout,
            "noImprovement": self.no_improvement,
            "infeasible": self.infeasible,
            "running": self.running,
            "successRate": percentage(self.completed, self.terminal),
            "hardValidRate": percentage(self.hard_valid_true, self.hard_valid_known),
            "appliedRate": percentage(self.applied_true, self.applied_known),
            "targetReachedRate": percentage(self.target_true, self.target_known),
            "floorReachedRate": percentage(self.floor_true, self.floor_known),
            "runtimeMs": {"samples": self.runtimes.len(), "p50": p50, "p95": p95},
            "metric": {
                "samples": self.metric_samples,
                "deltaSum": self.metric_delta_sum,
                "deltaAverage": if self.metric_samples == 0 { Value::Null } else { json!(round2(self.metric_delta_sum as f64 / self.metric_samples as f64)) },
                "beforeSum": self.metric_before_sum,
                "afterSum": self.metric_after_sum,
                "targetSamples": self.target_metric_samples,
                "targetSum": self.target_metric_sum,
                "floorSamples": self.floor_metric_samples,
                "floorSum": self.floor_metric_sum
            },
            "estimatedCostUsd": round6(self.cost_estimate_usd)
        })
    }
}

fn bool_count(value: Option<bool>, known: &mut u64, true_count: &mut u64) {
    if let Some(value) = value {
        *known += 1;
        if value {
            *true_count += 1;
        }
    }
}

#[derive(Default)]
struct Aggregate {
    overall: AggregateDimension,
    by_executor: BTreeMap<String, AggregateDimension>,
    by_focus: BTreeMap<String, AggregateDimension>,
    by_executor_focus_budget: BTreeMap<(String, String, String, String, u64), AggregateDimension>,
    by_outcome: BTreeMap<String, AggregateDimension>,
    by_result_kind: BTreeMap<String, AggregateDimension>,
    by_fallback: BTreeMap<String, AggregateDimension>,
    by_budget: BTreeMap<String, AggregateDimension>,
    by_metric: BTreeMap<String, AggregateDimension>,
    cloud_dimensions: BTreeMap<(String, String, String), AggregateDimension>,
    browser_events: u64,
    server_events: u64,
    deep_runs: u64,
}

impl Aggregate {
    fn add(&mut self, row: TelemetryRow) {
        self.overall.add(&row);
        self.by_executor
            .entry(row.executor.clone())
            .or_default()
            .add(&row);
        let focus_key = if row.gap_target.is_empty() {
            row.focus.clone()
        } else {
            format!("{}:{}", row.focus, row.gap_target)
        };
        self.by_focus.entry(focus_key).or_default().add(&row);
        self.by_executor_focus_budget
            .entry((
                row.executor.clone(),
                row.focus.clone(),
                row.gap_target.clone(),
                row.budget_kind.clone(),
                row.budget_seconds,
            ))
            .or_default()
            .add(&row);
        self.by_outcome
            .entry(row.outcome.clone())
            .or_default()
            .add(&row);
        self.by_result_kind
            .entry(row.result_kind.clone())
            .or_default()
            .add(&row);
        self.by_fallback
            .entry(row.fallback.clone())
            .or_default()
            .add(&row);
        self.by_budget
            .entry(format!("{}:{}s", row.budget_kind, row.budget_seconds))
            .or_default()
            .add(&row);
        if let Some(metric_key) = row.metric_key.clone() {
            self.by_metric.entry(metric_key).or_default().add(&row);
        }
        if row.source == "browser" {
            self.browser_events += 1;
        } else {
            self.server_events += 1;
        }
        if row.budget_kind == "deep" {
            self.deep_runs += 1;
        }
        if row.executor == "cloud_run" {
            let profile = row.profile.clone().unwrap_or_else(|| "unknown".to_string());
            let revision = row
                .cloud_revision
                .clone()
                .unwrap_or_else(|| "unknown".to_string());
            let digest = row
                .cloud_digest
                .clone()
                .unwrap_or_else(|| "unknown".to_string());
            self.cloud_dimensions
                .entry((profile, revision, digest))
                .or_default()
                .add(&row);
        }
    }

    fn json(self, window: &str, since_ms: u64, generated_at_ms: u64) -> Value {
        let total = self.overall.total;
        let cloud_dimensions = self
            .cloud_dimensions
            .into_iter()
            .map(|((profile, revision, digest), dimension)| {
                json!({
                    "profile": profile,
                    "revision": revision,
                    "digest": digest,
                    "aggregate": dimension.json()
                })
            })
            .collect::<Vec<_>>();
        let by_executor_focus_budget = self
            .by_executor_focus_budget
            .into_iter()
            .map(|((executor, focus, gap_target, budget_kind, budget_seconds), dimension)| {
                json!({
                    "executor": executor,
                    "focus": focus,
                    "gapTarget": if gap_target.is_empty() { Value::Null } else { json!(gap_target) },
                    "budgetKind": budget_kind,
                    "budgetSeconds": budget_seconds,
                    "aggregate": dimension.json()
                })
            })
            .collect::<Vec<_>>();
        json!({
            "ok": true,
            "window": window,
            "sinceMs": since_ms,
            "generatedAtMs": generated_at_ms,
            "retentionDays": RETENTION_MS / (24 * 60 * 60 * 1_000),
            "privacy": {
                "aggregateOnly": true,
                "doesNotStore": ["timetable", "request", "schoolId", "accountId", "userId", "rawError", "rawEventId"]
            },
            "events": {"total": total, "browser": self.browser_events, "server": self.server_events},
            "deepRunRate": percentage(self.deep_runs, total),
            "overall": self.overall.json(),
            "byExecutor": dimensions_json(self.by_executor),
            "byFocus": dimensions_json(self.by_focus),
            "byExecutorFocusBudget": by_executor_focus_budget,
            "byOutcome": dimensions_json(self.by_outcome),
            "byResultKind": dimensions_json(self.by_result_kind),
            "byFallback": dimensions_json(self.by_fallback),
            "byBudget": dimensions_json(self.by_budget),
            "byMetric": dimensions_json(self.by_metric),
            "cloud": cloud_dimensions
        })
    }
}

fn dimensions_json(dimensions: BTreeMap<String, AggregateDimension>) -> Vec<Value> {
    dimensions
        .into_iter()
        .map(|(key, dimension)| json!({"key": key, "aggregate": dimension.json()}))
        .collect()
}

fn percentile(values: &[u64], percentile: f64) -> Value {
    if values.is_empty() {
        return Value::Null;
    }
    let mut values = values.to_vec();
    values.sort_unstable();
    let rank = ((values.len() as f64 * percentile).ceil() as usize).saturating_sub(1);
    json!(values[rank.min(values.len().saturating_sub(1))])
}

fn percentage(numerator: u64, denominator: u64) -> Value {
    if denominator == 0 {
        Value::Null
    } else {
        json!(round2(numerator as f64 * 100.0 / denominator as f64))
    }
}

fn round2(value: f64) -> f64 {
    (value * 100.0).round() / 100.0
}

fn round6(value: f64) -> f64 {
    (value * 1_000_000.0).round() / 1_000_000.0
}

