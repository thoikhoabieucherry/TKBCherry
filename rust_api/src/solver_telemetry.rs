fn now_millis() -> u64 {
    SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .map(|value| value.as_millis().min(u64::MAX as u128) as u64)
        .unwrap_or(0)
}

fn digest_event_id(domain: &str, value: &str) -> String {
    let mut hasher = Sha256::new();
    hasher.update(b"tkb-solver-telemetry-v1\0");
    hasher.update(domain.as_bytes());
    hasher.update(b"\0");
    hasher.update(value.as_bytes());
    hasher
        .finalize()
        .iter()
        .map(|byte| format!("{byte:02x}"))
        .collect()
}

fn generated_event_key() -> String {
    // OS CSPRNG-backed token from the authentication module is held only while
    // creating this hash.  The raw token never crosses an API or database
    // boundary.
    digest_event_id("server", &crate::auth::random_token())
}

#[derive(Default)]
struct FetRateLimiter {
    buckets: Mutex<HashMap<String, RateBucket>>,
}

#[derive(Clone, Copy)]
struct RateBucket {
    window_started_ms: u64,
    count: u32,
    touched_ms: u64,
}

impl FetRateLimiter {
    fn allow(&self, actor_key: &str, client_ip: &str, now_ms: u64) -> bool {
        let bucket_key = digest_event_id("fet-rate", &format!("{actor_key}\0{client_ip}"));
        let Ok(mut buckets) = self.buckets.lock() else {
            // Failing closed here prevents a mutex poisoning event from making
            // the endpoint an unbounded write primitive.
            return false;
        };
        let stale_before = now_ms.saturating_sub(RATE_WINDOW_MS.saturating_mul(2));
        if buckets.len() > 4_096 {
            buckets.retain(|_, bucket| bucket.touched_ms >= stale_before);
        }
        let bucket = buckets.entry(bucket_key).or_insert(RateBucket {
            window_started_ms: now_ms,
            count: 0,
            touched_ms: now_ms,
        });
        if now_ms.saturating_sub(bucket.window_started_ms) >= RATE_WINDOW_MS {
            bucket.window_started_ms = now_ms;
            bucket.count = 0;
        }
        bucket.touched_ms = now_ms;
        if bucket.count >= FET_EVENTS_PER_WINDOW {
            return false;
        }
        bucket.count += 1;
        true
    }
}

fn fet_rate_limiter() -> &'static FetRateLimiter {
    static LIMITER: OnceLock<FetRateLimiter> = OnceLock::new();
    LIMITER.get_or_init(FetRateLimiter::default)
}

