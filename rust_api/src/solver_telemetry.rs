fn gap_distribution_value(metrics: &Map<String, Value>, minimum: i64) -> Option<i64> {
    let distribution = metrics.get("gap_distribution")?.as_object()?;
    let mut total = 0_i64;
    let mut found = false;
    for (gap, count) in distribution {
        let Ok(gap) = gap.parse::<i64>() else {
            continue;
        };
        if gap >= minimum {
            total = total.checked_add(nonnegative_metric(count)?)?;
            found = true;
        }
    }
    found.then_some(total)
}

